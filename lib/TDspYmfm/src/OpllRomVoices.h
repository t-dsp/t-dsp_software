// OpllRomVoices.h — the 15 built-in OPLL (YM2413) ROM instruments expressed as
// 8-byte USER-VOICE register sets ($00..$07), so the pool engine can load them into
// a chip's user voice and then MODULATE them (per-note timbre). A ROM voice selected
// the normal way ($3x nibble) is immutable; the same 8 bytes loaded as the user voice
// are fully tweakable.
//
// Bytes are ymfm's ym2413::s_default_instruments (the copyright-free plgDavid /
// David Viens ROM patch set, see lib/TDspYmfm/patches/pss140/NOTICE.md for the same
// provenance family). Instruments 1..15 only (the 3 trailing rhythm entries are the
// drum section, not melodic voices).
#pragma once
#include <stdint.h>

static constexpr int kOpllRomCount = 15;

